    public static string Localize(string code, string fallback)
    {
        // Chọn thông báo lỗi theo locale nhưng giữ nguyên mã lỗi kỹ thuật.
        if (!CultureInfo.CurrentUICulture.Name.StartsWith("vi", StringComparison.OrdinalIgnoreCase))
        {
            return fallback;
        }

        return Vietnamese.GetValueOrDefault(code, fallback);
    }

    public static string LocalizeValidationMessage(string message)
    {
        // Không trả chi tiết parser nội bộ; chỉ phân biệt trường bắt buộc và giá trị sai.
        var required = message.Contains("required", StringComparison.OrdinalIgnoreCase);
        var vietnamese = CultureInfo.CurrentUICulture.Name.StartsWith(
            "vi",
            StringComparison.OrdinalIgnoreCase);

        if (required)
        {
            return vietnamese
                ? "Trường này là bắt buộc."
                : "This field is required.";
        }

        return vietnamese
            ? "Giá trị đầu vào không hợp lệ."
            : "The input value is invalid.";
    }
